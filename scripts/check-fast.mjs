#!/usr/bin/env node
// ARCH-30, QUAL-24: the iteration check. It runs only what the diff reaches
// and never widens to the whole unit suite; CI and the nightly flake pass
// carry the wide runs.
//
//   guards         the cheap source guards, always.
//   units          `vitest related` over the diff (scripts/unit-scope.mjs,
//                  mode 'local'). What would make CI run everything is only
//                  noted; an empty diff or no usable base skips units.
//   typecheck      always `tsc --noEmit` (incremental), after `astro sync`
//                  when `.astro/types.d.ts` is not generated yet.
//
//   --since <ref>  scopes the diff to the working tree against <ref>
//                  (untracked files included), so a subagent given a task's
//                  starting commit tests its own edit. A ref that does not
//                  resolve, or is not an ancestor of HEAD, FAILS. Without it
//                  the base is the merge-base with origin/main.
//
// It always ends with one PASS/FAIL summary line, so an agent never re-runs it to find out
// whether it passed.
//
// Usage: npm run check:fast [-- --since <ref>]

import { existsSync, mkdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve as resolvePath } from 'node:path';
import { resolveBase, changedFilesWithStatus } from './change-scope.mjs';
import { selectUnitTests, runUnitByImpact } from './unit-scope.mjs';

const ROOT = resolvePath(dirname(fileURLToPath(import.meta.url)), '..');

// The cheap source guards check:fast has always run, in the same order.
export const GUARD_STEPS = [
  'check:backlog',
  'check:guidance',
  'check:never-say',
  'test:editor-dependency-directions',
  'test:module-boundaries',
  'test:ratchet-raises',
  'test:size-ratchet',
  'test:hook-ratchet',
  'test:any-ratchet',
  'test:ts-nocheck-ratchet',
  'test:e2e-sleeps',
  'test:unused-exports',
  'test:untested-modules',
  'test:gesture-golden-rule',
  'test:swallowed-errors',
  'test:navigating-away',
  'test:detection-purity',
  'check-class-resolution',
];

// Pure. `.astro/types.d.ts` (generated by astro, included by tsconfig) must be
// on disk for tsc to read; otherwise sync it first.
export function typecheckSteps({ astroTypesExist }) {
  return astroTypesExist ? ['tsc'] : ['astro-sync', 'tsc'];
}

// Pure. The units detail for the summary line.
export function unitsDetail(scope) {
  return scope.seeds.length > 0 ? `${scope.seeds.length} seeds` : 'skipped';
}

// Pure. Returns { since } or { error }.
export function parseArgs(argv) {
  const i = argv.indexOf('--since');
  if (i < 0) return { since: undefined };
  const since = argv[i + 1];
  if (!since || since.startsWith('--')) return { error: '--since needs a ref (the commit the task started from)' };
  return { since };
}

// Pure. One line: verdict, total, base, per-step seconds.
export function summaryLine({ ok, failed, base, since, steps }) {
  const total = steps.reduce((sum, s) => sum + s.seconds, 0);
  const verdict = ok ? 'PASS' : `FAIL at ${failed}`;
  const scope = since ? `since ${since}` : `since merge-base ${base ? base.slice(0, 7) : '(none)'}`;
  const parts = steps.map((s) => `${s.name} ${s.seconds.toFixed(1)}s${s.detail ? ` (${s.detail})` : ''}`);
  return `check:fast ${verdict} in ${total.toFixed(1)}s, ${scope}: ${parts.join(', ')}`;
}

// ---------------------------------------------------------------------------
// I/O below: git, npm and npx subprocesses. The pure parts above are pinned by
// scripts/check-fast.test.mjs.

function run(cmd, args) {
  return spawnSync(cmd, args, { stdio: 'inherit', cwd: ROOT }).status ?? 1;
}

function runGuard(step) {
  if (step === 'check-class-resolution') return run('node', ['scripts/check-class-resolution.js']);
  return run('npm', ['run', '-s', step]);
}

// Exported for check-push.mjs (ARCH-31), which makes the same choice.
export function runTypecheck(tool) {
  if (tool === 'astro-sync') return run('npx', ['astro', 'sync']);
  const cacheDir = join(ROOT, 'node_modules', '.cache');
  mkdirSync(cacheDir, { recursive: true });
  return run('npx', ['tsc', '--noEmit', '-p', '.', '--incremental', '--tsBuildInfoFile', join(cacheDir, 'check-fast.tsbuildinfo')]);
}

// Returns null when usable, else the failure reason. A ref that resolves but
// is not an ancestor of HEAD (a mis-copied SHA, a rebase since the task
// started) would silently shrink the diff, so it fails like an unresolvable one.
function sinceProblem(since) {
  if (since === undefined) return null;
  const resolves = spawnSync('git', ['rev-parse', '--verify', '--quiet', `${since}^{commit}`], { cwd: ROOT, stdio: 'ignore' }).status === 0;
  if (!resolves) return `--since ${since} does not resolve`;
  const ancestor = spawnSync('git', ['merge-base', '--is-ancestor', since, 'HEAD'], { cwd: ROOT, stdio: 'ignore' }).status === 0;
  return ancestor ? null : `--since ${since} is not an ancestor of HEAD`;
}

function timed(fn) {
  const start = performance.now();
  const status = fn();
  return { status, seconds: (performance.now() - start) / 1000 };
}

function main(argv) {
  const args = parseArgs(argv);
  if (args.error) {
    console.log(`check:fast FAIL: ${args.error}`);
    return 2;
  }

  const problem = sinceProblem(args.since);
  if (problem) {
    console.log(`check:fast FAIL: ${problem}`);
    return 2;
  }

  const base = resolveBase(args.since);
  const files = base ? changedFilesWithStatus(base) : null;
  const unitScope = files
    ? selectUnitTests({ files, exists: (p) => existsSync(join(ROOT, p)), mode: 'local' })
    : { all: false, seeds: [], reasons: ['no usable base: unit tests skipped, CI runs them'] };
  const typecheck = typecheckSteps({ astroTypesExist: existsSync(join(ROOT, '.astro', 'types.d.ts')) });

  const plan = [
    { name: 'guards', run: () => GUARD_STEPS.reduce((status, step) => status || runGuard(step), 0) },
    {
      name: 'units',
      detail: unitsDetail(unitScope),
      run: () => {
        console.error(`check:fast units: ${unitScope.reasons.join(' | ')}`);
        return runUnitByImpact(unitScope);
      },
    },
    ...typecheck.map((tool) => ({ name: tool === 'tsc' ? 'tsc' : 'astro sync', run: () => runTypecheck(tool) })),
  ];

  const steps = [];
  let failed;
  for (const step of plan) {
    const { status, seconds } = timed(step.run);
    steps.push({ name: step.name, seconds, detail: step.detail });
    if (status !== 0) {
      failed = step.name;
      break;
    }
  }

  console.log(`\n${summaryLine({ ok: !failed, failed, base, since: args.since, steps })}`);
  return failed ? 1 : 0;
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  process.exit(main(process.argv.slice(2)));
}
