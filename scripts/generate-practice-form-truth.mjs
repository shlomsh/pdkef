import fs from 'node:fs';
import crypto from 'node:crypto';
import { PDFDocument, PDFName, PDFDict } from '@cantoo/pdf-lib';

/**
 * Regenerates the practice form's scoring ground truth from the form itself.
 *
 * The practice form is the one scored form that needs no annotation pass: it
 * is a live AcroForm, so each widget's `/Rect` IS the field, exact to the
 * point, and the field's own name says what it is for. That makes it the
 * cheapest honest ground truth we have and - since the other two scored forms
 * are Hebrew - the first Latin one.
 *
 * Kinds describe the FORM, not the detector. `parent_guardian_signature` is a
 * signature target and `signature_date` is a date target even though the
 * detector reports both as ordinary text today; a truth file written to match
 * what we already do would score 100% and measure nothing.
 *
 * Run: node scripts/generate-practice-form-truth.mjs
 */
const FILE = 'public/images/redaction-guide/sample.pdf';
const bytes = fs.readFileSync(FILE);
const doc = await PDFDocument.load(bytes, { ignoreEncryption: true });
const page = doc.getPage(0);
const { width: pw, height: ph } = page.getSize();
const ctx = doc.context;

const inherited = (w, key) => { let f = w, seen = new Set();
  while (f instanceof PDFDict && !seen.has(f)) { seen.add(f);
    const v = ctx.lookup(f.get(PDFName.of(key))); if (v !== undefined) return v;
    f = ctx.lookup(f.get(PDFName.of('Parent'))); } return undefined; };

// The form's own field names say what each field is for. A signature line is
// a signature target and a date field is a date target, whatever our detector
// currently reports them as - truth describes the form, not the detector.
const kindOf = (name, ft, ff, maxLen) => {
  if (ft === '/Btn') return 'checkbox';
  if ((ff & (1 << 24)) && maxLen > 1) return 'comb';
  // Order matters: `signature_date` is a date field that happens to carry the
  // word signature, so the more specific suffix test has to come first.
  if (/date$/i.test(name)) return 'date';
  if (/signature/i.test(name)) return 'signature';
  return 'text';
};

const annots = page.node.Annots();
const targets = [];
for (let i = 0; i < annots.size(); i += 1) {
  const w = ctx.lookup(annots.get(i));
  const nameRaw = inherited(w, 'T');
  const name = nameRaw?.decodeText?.() ?? nameRaw?.asString?.() ?? `field_${i}`;
  const ft = inherited(w, 'FT')?.asString?.();
  const ff = inherited(w, 'Ff')?.asNumber?.() ?? 0;
  const maxLen = inherited(w, 'MaxLen')?.asNumber?.();
  const r = ctx.lookup(w.get(PDFName.of('Rect')))?.asRectangle?.();
  const target = {
    id: `t${String(targets.length + 1).padStart(3, '0')}`,
    kind: kindOf(name, ft, ff, maxLen),
    // CONTRACT.md: x = x0/pageWidth, y = (pageHeight - yTop)/pageHeight.
    bounds: {
      x: +(r.x / pw).toFixed(4),
      y: +((ph - (r.y + r.height)) / ph).toFixed(4),
      width: +(r.width / pw).toFixed(4),
      height: +(r.height / ph).toFixed(4),
    },
    label: name,
    notes: 'from the form\'s own AcroForm widget: /Rect is the field, exact to the point',
  };
  if (target.kind === 'comb') target.cells = maxLen;
  targets.push(target);
}

const truth = {
  form: 'pdkef-practice-form',
  sha256: crypto.createHash('sha256').update(bytes).digest('hex'),
  sourceUrl: 'in-repo: public/images/redaction-guide/sample.pdf',
  pageIndex: 0,
  pageSize: { width: pw, height: ph },
  render: null,
  notes: 'Self-labelling: every target is one of the form\'s nine AcroForm widgets, so the bounds are exact rather than annotated, and no eyeballing pass was needed. Generated by scripts/generate-practice-form-truth.mjs; regenerate rather than hand-edit.',
  targets,
};
fs.writeFileSync('src/editor/adapters/pdf/corpus/scoring/ground-truth/practice-form-page1.json', JSON.stringify(truth, null, 1) + '\n');
console.log(`page ${pw}x${ph}, ${targets.length} targets:`, targets.map(t => `${t.kind}:${t.label}`).join(', '));
