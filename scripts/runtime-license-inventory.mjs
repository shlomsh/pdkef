import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packageJsonPath = path.join(root, 'package.json');
const lockfilePath = path.join(root, 'package-lock.json');
const noticesPath = path.join(root, 'THIRD_PARTY_LICENSES.md');
const clientInventoryPath = path.join(root, 'src', 'data', 'runtimeLicenseInventory.js');
const BEGIN = '<!-- BEGIN GENERATED RUNTIME PACKAGE NOTICES -->';
const END = '<!-- END GENERATED RUNTIME PACKAGE NOTICES -->';

// This is a deliberately narrow policy allowlist. Adding an identifier needs
// a human review; a package being open source is not approval by itself.
export const APPROVED_RUNTIME_LICENSES = new Set([
  'MIT', 'Apache-2.0', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Zlib', '0BSD', '(MIT AND Zlib)',
]);

// Every production dependency must be reviewed here. Astro and its Preact
// integration are browser runtime packages, but their compiler/dev-server
// dependency trees are build-only and deliberately not traversed below.
export const RUNTIME_ROOT_PACKAGES = [
  '@astrojs/preact', '@cantoo/pdf-lib', '@floating-ui/dom', '@floating-ui/react', '@pdf-lib/fontkit',
  '@vercel/analytics', 'astro', 'bidi-js', 'lucide-preact', 'pdfjs-dist', 'preact',
  'regenerator-runtime', 'signature_pad', 'sortablejs',
];

const BUILD_ONLY_CLOSURES = new Set(['astro', '@astrojs/preact']);

// The complete browser-code closure of the roots above. New transitive code
// must be added explicitly after review, rather than inheriting approval from
// its parent package. The two signal packages are emitted by Astro's client.
export const RUNTIME_PACKAGE_NAMES = [
  ...RUNTIME_ROOT_PACKAGES,
  '@preact/signals', '@preact/signals-core', '@pdf-lib/standard-fonts', '@pdf-lib/upng',
  '@floating-ui/core', '@floating-ui/react-dom', '@floating-ui/utils', 'color', 'color-convert',
  'color-name', 'color-string', 'html-entities', 'is-arrayish',
  'node-html-better-parser', 'pako', 'require-from-string', 'simple-swizzle', 'tabbable', 'tslib',
].sort((a, b) => a.localeCompare(b));

const LICENSE_URL_OVERRIDES = {
  // The published tarball declares MIT but does not carry a license file.
  '@pdf-lib/fontkit': 'https://github.com/Hopding/fontkit/blob/master/LICENSE',
};

function packageDirectory(name) { return path.join(root, 'node_modules', ...name.split('/')); }
function readPackage(name) { return JSON.parse(fs.readFileSync(path.join(packageDirectory(name), 'package.json'), 'utf8')); }
function packageUrl(pkg) {
  const source = pkg.homepage || pkg.repository?.url || pkg.repository;
  if (!source) return `https://www.npmjs.com/package/${pkg.name}/v/${pkg.version}`;
  const normalized = String(source)
    .replace(/^github:/, 'https://github.com/')
    .replace(/^git\+/, '')
    .replace(/^git:\/\//, 'https://')
    .replace(/\.git$/, '');
  return /^[\w.-]+\/[\w.-]+$/.test(normalized) ? `https://github.com/${normalized}` : normalized;
}
function licenseText(name) {
  const dir = packageDirectory(name);
  const entries = fs.readdirSync(dir);
  const file = entries.find((entry) => /^license(\.|$)/i.test(entry))
    ?? entries.find((entry) => /^(copying|notice|copyright)(\.|$)/i.test(entry));
  return file
    ? fs.readFileSync(path.join(dir, file), 'utf8').trim().split(/\r?\n/).map((line) => line.trimEnd()).join('\n')
    : null;
}

export function runtimePackageInventory() {
  return RUNTIME_PACKAGE_NAMES.map((name) => {
    const pkg = readPackage(name);
    return {
      name, version: pkg.version, license: pkg.license, url: packageUrl(pkg),
      author: typeof pkg.author === 'string' ? pkg.author : pkg.author?.name ?? 'See upstream notice',
      notice: licenseText(name), noticeUrl: LICENSE_URL_OVERRIDES[name] ?? packageUrl(pkg),
    };
  });
}

function clientInventorySource() {
  const packages = runtimePackageInventory().map(({ name, version, license, url }) => ({ name, version, license, url }));
  return `// GENERATED by scripts/runtime-license-inventory.mjs. Do not edit by hand.\nexport const RUNTIME_LICENSE_PACKAGES = ${JSON.stringify(packages, null, 2)};\n`;
}

function runtimeNoticeBlock() {
  const packages = runtimePackageInventory();
  const table = packages.map((pkg) => `| [${pkg.name}](${pkg.url}) | ${pkg.version} | ${pkg.license} |`).join('\n');
  const notices = packages.map((pkg) => {
    const body = pkg.notice
      ? `\`\`\`\n${pkg.notice}\n\`\`\``
      : `The published package metadata declares \`${pkg.license}\`. Its upstream license notice is <${pkg.noticeUrl}>.`;
    return `### ${pkg.name} (${pkg.version}) - ${pkg.license}\n\n${pkg.author}\n\n${body}`;
  }).join('\n\n');
  return `${BEGIN}\n## Browser-shipped JavaScript inventory\n\nThis generated inventory covers direct app dependencies, the browser-side Astro/Preact runtime, and every transitive package reached by browser code. Astro's compiler and dev-server dependency tree is build-only and excluded. Run \`npm run generate:licenses\` after an approved dependency change; \`npm run test:licenses\` fails on stale notices, versions, licenses, or unreviewed packages.\n\nThe approved runtime licenses are MIT, Apache-2.0, ISC, BSD-2-Clause, BSD-3-Clause, Zlib, and 0BSD. This is a reviewed permissive policy, not automatic approval of every open-source license.\n\n| Package | Locked version | License |\n| --- | --- | --- |\n${table}\n\n## Runtime package notices\n\n${notices}\n${END}`;
}

function runtimeDependencyClosure() {
  const seen = new Set();
  const visit = (name) => {
    if (seen.has(name)) return;
    seen.add(name);
    if (BUILD_ONLY_CLOSURES.has(name)) return;
    for (const dependency of Object.keys(readPackage(name).dependencies ?? {})) visit(dependency);
  };
  RUNTIME_ROOT_PACKAGES.forEach(visit);
  seen.add('@preact/signals');
  seen.add('@preact/signals-core');
  return [...seen].sort((a, b) => a.localeCompare(b));
}

export function verifyRuntimeLicenses() {
  const errors = [];
  const direct = Object.keys(JSON.parse(fs.readFileSync(packageJsonPath, 'utf8')).dependencies ?? {}).sort();
  const roots = [...RUNTIME_ROOT_PACKAGES].sort();
  if (JSON.stringify(direct) !== JSON.stringify(roots)) errors.push(`package.json runtime dependencies differ from reviewed roots. Expected: ${roots.join(', ')}. Actual: ${direct.join(', ')}.`);
  const actualClosure = runtimeDependencyClosure();
  if (JSON.stringify(actualClosure) !== JSON.stringify(RUNTIME_PACKAGE_NAMES)) errors.push(`Browser runtime closure differs from reviewed inventory. Expected: ${RUNTIME_PACKAGE_NAMES.join(', ')}. Actual: ${actualClosure.join(', ')}.`);
  const lockfile = JSON.parse(fs.readFileSync(lockfilePath, 'utf8'));
  for (const pkg of runtimePackageInventory()) {
    const lock = lockfile.packages[`node_modules/${pkg.name}`];
    if (!lock) errors.push(`${pkg.name} is absent from package-lock.json.`);
    else if (lock.version !== pkg.version) errors.push(`${pkg.name} lockfile version ${lock.version} does not match installed ${pkg.version}.`);
    if (!APPROVED_RUNTIME_LICENSES.has(pkg.license)) errors.push(`${pkg.name}@${pkg.version} declares unapproved license ${pkg.license}.`);
    if (!pkg.notice && !LICENSE_URL_OVERRIDES[pkg.name]) errors.push(`${pkg.name}@${pkg.version} has no local or reviewed upstream license notice.`);
  }
  const document = fs.readFileSync(noticesPath, 'utf8');
  const start = document.indexOf(BEGIN);
  const end = document.indexOf(END);
  const actual = start === -1 || end === -1 ? null : document.slice(start, end + END.length);
  if (actual !== runtimeNoticeBlock()) errors.push('THIRD_PARTY_LICENSES.md runtime notice block is stale. Run npm run generate:licenses and review the diff.');
  if (!fs.existsSync(clientInventoryPath) || fs.readFileSync(clientInventoryPath, 'utf8') !== clientInventorySource()) {
    errors.push('src/data/runtimeLicenseInventory.js is stale. Run npm run generate:licenses and review the diff.');
  }
  return errors;
}

function writeNotices() {
  const document = fs.readFileSync(noticesPath, 'utf8');
  const block = runtimeNoticeBlock();
  const start = document.indexOf(BEGIN);
  const end = document.indexOf(END);
  const next = start !== -1 && end !== -1
    ? `${document.slice(0, start)}${block}${document.slice(end + END.length)}`
    : document.replace(/^## Astro[\s\S]*?(?=^## Handwriting Fonts)/m, `${block}\n\n`);
  fs.writeFileSync(noticesPath, next);
  fs.writeFileSync(clientInventoryPath, clientInventorySource());
}

if (process.argv.includes('--write')) {
  writeNotices();
  console.log(`Generated runtime license notices for ${RUNTIME_PACKAGE_NAMES.length} browser packages.`);
} else if (process.argv.includes('--check')) {
  const errors = verifyRuntimeLicenses();
  if (errors.length) {
    console.error(`Runtime license check failed:\n- ${errors.join('\n- ')}`);
    process.exit(1);
  }
  console.log(`Runtime license inventory is current (${RUNTIME_PACKAGE_NAMES.length} browser packages).`);
}
